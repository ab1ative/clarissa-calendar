"""Step 3. Split each edition's text into letters, with their headings, datelines and notes.

Input:  work/<ed>_para.txt (step 2) for the body; work/<ed>.txt (step 1) for the NOTES section.
Output: work/letters.json = {"1": [letter, ...], "3": [letter, ...]}, each letter
        {ed, vol, num, seq, printed, note, addr, date, text, notes[, summary]}
          num      letter number within its volume (corrected where the printing misnumbers)
          printed  the Roman numeral as printed (None for items without a heading)
          note     remark on a misnumbered heading, or on an editor's summary
          addr     heading: writer and recipient ("Miss Howe, To Miss Clarissa Harlowe.")
          date     dateline as printed ("Harlowe-Place, Jan. 13.")
          text     paragraphs joined by "\\n"; footnote references as \\uE000N\\uE001
          notes    [[serial, mark, text], ...] for the references in this letter

Footnotes: ProQuest moves Richardson's footnotes to a NOTES section at the end and leaves
"(a) 91" in the text: Richardson's mark plus ProQuest's serial number. Notes whose text is an
arrow are his pointing hands (☞). A few notes have no mark at all (three verse quotations in
L261); their reference is the bare serial number.

Editor's summaries: in 1748 Richardson sometimes summarised a letter instead of printing it.
The transcription runs each summary on at the end of the preceding letter; where 1751 prints
the full letter instead, the summary is split out as its own item (summary=True).
"""
import re
from common import work, save, to_roman, from_roman

FOOTER = re.compile(r'PDF GENERATED BY PROQUEST\.COM')
VOL = re.compile(r'^\s*Vol\. (\d+)\s*$')
HEAD = re.compile(r'^\s*·?\s*LETTER\.?\s+([IVXLC]+)\.?\s*$')
BARE = re.compile(r'^\s*([IVXLC]{2,})\.\s*$')            # heading without "LETTER", e.g. "LXXXVIII."
CHAP = re.compile(r'^\s*CHAP\.\s+([IVXLC]+)\.\s*$')      # transcription slip for LETTER
ADDR = re.compile(r'^\s*[A-Z][^\n]{2,80}?,?\s+[Tt]o\s+((the|her|his|my) )?[A-Z].{2,90}$')
HDR = re.compile(r'^(To |From |Superscribed|Translation of|\[?Inclosed|.*In Cou?ntinuation|In (Continuation|Answer|Reply)'
                 r'|.*[;.,]\s*In (Continuation|Answer|Reply))')
BRACKETED = re.compile(r'^[\[(].{3,90}[\])]\.?$')
DAYS = r'(Sun|Mond?|Tues?|Wedn?(es)?|Thur(s)?d?|Frid?|Sat(ur)?)(day)?\b\.?'
MONTHS = r'(Jan|Feb|March|Mar|Apr|April|May|June|July|Aug|Sept?|Oct|Nov|Dec)'
DATE = re.compile(rf'^\[?({DAYS}|{MONTHS}|[A-Z][\w\'\-. ]{{1,40}},\s*({DAYS}|{MONTHS})|Midnight|Past|Near|Two|Three|Four'
                  rf'|Five|Six|Seven|Eight|Nine|Ten|Eleven|Twelve).{{0,70}}$')
# Sections that end a volume's run of letters (case-sensitive on purpose: "The end of..." in a letter is not one)
STOP = re.compile(r'^\s*(CONCLUSION\.?\s*$|END of V(OL|ol)\.|\[Errata|The Remainder of this Work will|A COLLECTION Of'
                  r'|CONTENTS of Vol|TABLE to the|THE END\.?\s*$|ERRATA\.?\s*$|NOTES\s*$|ProQuest document link)')
S0, S1 = '', ''


def load_lines(path):
    """Lines of a text file, without ProQuest footers and printed-page markers."""
    out = []
    for l in open(path, encoding='utf-8', errors='replace'):
        if FOOTER.search(l):
            continue
        out.append(re.sub(r'\s*\[Page [^\]]*\]\s*', ' ', l.rstrip('\n')).strip())
    return out


NOTE_LINE = re.compile(r'^(\d+)(?: \[([^\]]*)\])?(?: \(([^)]*)\))?(?: (.*))?$')

def read_notes(lines):
    """{serial: [mark, text]} from the NOTES section."""
    start = max(i for i, l in enumerate(lines) if l.strip() == 'NOTES')
    notes, cur = {}, None
    for l in lines[start + 1:]:
        if not l.strip():
            continue
        m = NOTE_LINE.match(l.strip())
        if m and (cur or 0) < int(m.group(1)) <= (cur or 0) + 8:     # serials run in order, with small gaps
            cur = int(m.group(1))
            mark, text = m.group(3) or m.group(2) or '', (m.group(4) or '').strip()
            if text in ('←', '☞') or mark in ('←', '☞'):
                mark, text = '☞', ''
            notes[cur] = [mark, text]
        elif cur:
            notes[cur].append(l.strip())                        # continuation line, joined below
    for n, (mark, *rest) in notes.items():
        lines_ = [x for x in rest if x]
        verse = len(lines_) > 1 and all(len(x) < 60 for x in lines_)   # short lines: a verse quotation
        notes[n] = [mark, (' / ' if verse else ' ').join(lines_)]
    # The mark sometimes sits at the start of the text, or is printed twice ("[a] (a)").
    for n, (mark, text) in notes.items():
        if mark == '☞':
            continue
        while True:
            m = re.match(r'^\s*[\[(]([a-z*†‡§|]{1,4})[\])]\s*', text)
            if not m:
                break
            mark, text = m.group(1), text[m.end():]
        if text.strip() in ('←', '☞'):
            mark, text = '☞', ''
        notes[n] = [mark, text.strip()]
    return notes


def mark_refs(lines, notes, ed):
    """Replace each note reference in the body with a sentinel, walking forward in serial order."""
    end = max(i for i, l in enumerate(lines) if l.strip() == 'NOTES')
    text, pos, missing = '\n'.join(lines[:end]), 0, []
    for n in sorted(notes):
        mark = notes[n][0]
        if mark and mark != '☞':     # "(a) 91", "( b) 24", "(a ) 45", "(a).\n444"
            pat = re.compile(r'[ \t]*[\[(]\s*' + re.escape(mark) + r'\s*[\])]\.?\s?' + str(n) + r'(?!\d)')
        else:                         # pointing hand or unmarked note: the bare serial
            pat = re.compile(r'(?<!Page )(?<!Vol\. )(?<![\w\[])' + str(n) + r'(?![\w\]])')
        m = pat.search(text, pos)
        if not m or m.start() - pos > 400000:
            missing.append(n); continue
        sent = S0 + str(n) + S1
        text = text[:m.start()] + (' ' if mark and mark != '☞' else '') + sent + text[m.end():]
        pos = m.start() + len(sent)
    if missing:
        print(f'  {ed}: note references not found:', missing[:20], len(missing))
    return text.split('\n')


def split_letters(ed):
    lines = load_lines(work(f'{ed}_para.txt'))
    notes = read_notes(load_lines(work(f'{ed}.txt')))
    lines = mark_refs(lines, notes, ed)
    vol, letters, cur, stopped, seq, expect = 0, [], None, False, 0, 1
    for l in lines:
        m = VOL.match(l)
        if m:
            vol, expect, stopped, cur = int(m.group(1)), 1, False, None
            continue
        if not vol:
            continue
        num = None
        m = HEAD.match(l) or CHAP.match(l) or BARE.match(l)
        if m:
            n = from_roman(m.group(1))
            if HEAD.match(l) or n == expect:      # CHAP/BARE count only as the next expected number
                num, printed = n, m.group(1)
        if num is not None:
            note, shown = None, num
            if num > expect:
                note = (f'The {"1748" if ed == "1" else "1751"} printing skips from LETTER {to_roman(expect - 1)} '
                        f'to LETTER {printed}; no letter is missing.')
            elif num < expect:
                shown = expect
                note = f'Misprinted as LETTER {printed} in the original; it is the {expect}th letter of the volume.'
            seq += 1
            cur = {'ed': ed, 'vol': vol, 'num': shown, 'seq': seq, 'printed': printed, 'note': note, 'lines': []}
            letters.append(cur); expect = shown + 1; stopped = False
            continue
        if cur is not None and not stopped:
            if STOP.match(l):
                stopped = True
            else:
                cur['lines'].append(l)
    return [finish(L, notes) for L in letters], notes


def finish(L, notes):
    """Separate heading, notes in brackets and dateline from the body; tidy the paragraphs."""
    body = [b.strip() for b in L.pop('lines')]
    while body and not body[0]: body.pop(0)
    while body and not body[-1]: body.pop()
    clean = lambda x: x.replace('·', '').strip()
    addr, date = [], ''
    while body and len(addr) < 3:
        h = clean(body[0])
        if not h:
            body.pop(0); continue
        nxt = clean(next((x for x in body[1:4] if x), ''))
        if (len(h) < 90 and (ADDR.match(h) or HDR.match(h))) or (h.startswith('To ') and len(h) < 220) \
                or (len(h) < 50 and re.match(r'^In (Continuation|Answer|Reply)', nxt)):
            addr.append(clean(body.pop(0))); continue
        break
    bracketed = []
    while body and (not body[0] or (BRACKETED.match(clean(body[0])) and len(bracketed) < 2)):
        x = clean(body.pop(0))
        if x: bracketed.append(x)
    if body and DATE.match(clean(body[0])):
        date = clean(body.pop(0))
    addr = ' '.join(addr + bracketed)
    addr = re.sub(S0 + r'\d+' + S1, '', addr).strip()          # a note on the heading is not kept
    date = re.sub(S0 + r'\d+' + S1, '', date).strip()
    paras = []
    for p in body:
        p = re.sub(r'\s+', ' ', p).strip()
        marked = '·' in p                          # ProQuest's marginal dot: keep as a paragraph flag
        p = p.replace('·', '').strip()
        if p:
            paras.append(('· ' if marked else '') + p)
    text = '\n'.join(paras)
    text = re.sub(r'- (?=[a-z])', '-', text)                                   # words broken at line ends
    text = re.sub('[ \\t]+(' + S0 + r'\d+' + S1 + ')', r'\1', text)            # reference hugs its word
    text = re.sub('(' + S1 + r')[ \t]+([,.;:!?)\]’”])', r'\1\2', text)
    L.update(addr=addr, date=date, text=text)
    return L


SUMMARY = re.compile(r"^(· )?(The Lady|Mr\. Lovelace|Mr\. Belford|Miss Howe|Col(onel|\.) Morden)[,]? "
                     r"(in (her|his|three|two|several)\b[^.]{0,40}?(letter|letters|answer|reply)\b|writes again"
                     r"|to shew the wantonness)")
SUM_WRITER = {'The Lady': 'Miss Clarissa Harlowe, To Miss Howe', 'Mr. Lovelace': 'Mr. Lovelace, To John Belford, Esq;',
              'Mr. Belford': 'Mr. Belford, To Colonel Morden', 'Miss Howe': 'Miss Howe, To Miss Clarissa Harlowe'}

def grams(text):
    w = re.findall(r'[a-z]+', text.lower())
    return {' '.join(w[i:i + 5]) for i in range(len(w) - 4)}

def split_summaries(first, third):
    """Split a 1748 editor's summary off the end of the letter it is run on to, unless 1751 kept it."""
    raw3 = re.sub(r'\s+', ' ', ' '.join(L['text'] for L in third))
    g3 = grams(raw3)
    out = []
    for L in first:
        paras = L['text'].split('\n')
        k = next((i for i, p in enumerate(paras) if SUMMARY.match(p) and p[:60].lstrip('· ') not in raw3), None)
        if k is not None:
            g = grams(' '.join(paras[k:]))
            if g and sum(x in g3 for x in g) / len(g) > 0.4:     # 1751 kept it (perhaps revised)
                k = None
        if k is None:
            out.append(L); continue
        lead = SUMMARY.match(paras[k]).group(2)
        out.append(dict(L, text='\n'.join(paras[:k])))
        out.append({'ed': '1', 'vol': L['vol'], 'num': L['num'], 'seq': L['seq'], 'printed': None, 'summary': True,
                    'addr': SUM_WRITER.get(lead, lead), 'date': '', 'text': '\n'.join(paras[k:]),
                    'note': f"In 1748 this letter is not printed. Richardson, as editor, gives a summary in its place, "
                            f"set at the end of Vol. {L['vol']}, Letter {L['num']}."})
    return out


def run():
    a, notes1 = split_letters('1')
    b, notes3 = split_letters('3')
    a = split_summaries(a, b)
    for items, notes in ((a, notes1), (b, notes3)):      # notes go with the item holding the reference
        for L in items:
            L['notes'] = [[n] + notes[n] for n in map(int, re.findall(S0 + r'(\d+)' + S1, L['text']))]
    save({'1': a, '3': b}, work('letters.json'))
    for name, ed in (('1748', a), ('1751', b)):
        print(f'  {name}: {len(ed)} items, {sum(1 for L in ed if L.get("summary"))} summaries')

if __name__ == '__main__':
    run()
