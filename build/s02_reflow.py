"""Step 2. Rebuild paragraphs from the PDF's line geometry.

ProQuest sets the text ragged-right, so a line ends a paragraph exactly when the first word of
the next line would have fitted on it. Page breaks, blank lines and footers in pdftotext's plain
output are artefacts of the export, not paragraph breaks.

One case geometry can't settle: a line that runs to the margin and ends a sentence, followed by
a line starting with a capital. It may or may not end a paragraph. Such joins are marked with
SOFT (U+2063) and settled in step 6 by looking at where the other edition breaks.

Output: work/<ed>_para.txt, one paragraph (or heading) per line; "[Page N]" markers are kept so
step 3 can find the printed pages.
"""
import html
import re
from common import work

PAGE_RE = re.compile(r'<page width="([\d.]+)" height="([\d.]+)">(.*?)</page>', re.S)
LINE_RE = re.compile(r'<line xMin="([\d.]+)" yMin="([\d.]+)" xMax="([\d.]+)" yMax="([\d.]+)">(.*?)</line>', re.S)
WORD_RE = re.compile(r'<word xMin="([\d.]+)" yMin="[\d.]+" xMax="([\d.]+)" yMax="[\d.]+">(.*?)</word>', re.S)
FOOTER = re.compile(r'PDF GENERATED BY PROQUEST|^Page \d+ of \d+$')
MARKER_ONLY = re.compile(r'^\[Page [^\]]*\]$')
HEADING = re.compile(r'^(\[Page [^\]]*\]\s*)*(·?\s*LETTER\.?\s+[IVXLC]+\.?|Vol\. \d+|NOTES|CONCLUSION\.?|POSTSCRIPT\.?'
                     r'|CHAP\.\s+[IVXLC]+\.|[IVXLC]{2,}\.|FULL TEXT|Clarissa \((1st|3rd) ed\.\))\s*$')
SOFT = '⁣'     # possible paragraph break, settled in step 6
GAP = 3.0           # width of an inter-word space at this type size, in points


def read_lines(path):
    """All text lines of the PDF with their right edge, first-word width and page margin."""
    lines = []
    for _, _, body in PAGE_RE.findall(open(path, encoding='utf-8').read()):
        page = []
        for x0, y0, x1, y1, inner in LINE_RE.findall(body):
            words = [(float(a), float(b), html.unescape(t)) for a, b, t in WORD_RE.findall(inner)]
            words = [w for w in words if w[2] != '·']              # ProQuest's marginal dots
            if not words:
                continue
            text = ' '.join(w[2] for w in words)
            if FOOTER.search(text):
                continue
            page.append({'text': text, 'x1': max(w[1] for w in words), 'w0': words[0][1] - words[0][0],
                         'x0': words[0][0], 'y': float(y0)})
        if not page:
            continue
        # pdftotext sometimes splits one printed line into pieces; rejoin pieces on one baseline.
        page.sort(key=lambda l: (round(l['y']), l['x0']))
        merged = []
        for l in page:
            if merged and abs(merged[-1]['y'] - l['y']) < 2.0 and l['x0'] > merged[-1]['x1'] - 1:
                merged[-1]['text'] += ' ' + l['text']
                merged[-1]['x1'] = max(merged[-1]['x1'], l['x1'])
            else:
                merged.append(dict(l))
        right = max(l['x1'] for l in merged)
        for l in merged:
            l['right'] = right
        lines += merged
    return lines


def paragraphs(lines):
    out, buf = [], []
    def flush():
        if buf:
            out.append(' '.join(buf).replace(SOFT + ' ', SOFT).replace(' ' + SOFT, ' ' + SOFT).strip(' ' + SOFT))
        buf.clear()
    # The decision for each text line looks past standalone page markers to the next real line.
    real = [i for i, l in enumerate(lines) if not MARKER_ONLY.match(l['text'])]
    nxt = {real[k]: real[k + 1] for k in range(len(real) - 1)}
    for i, l in enumerate(lines):
        if MARKER_ONLY.match(l['text']):
            buf.append(l['text']); continue
        if HEADING.match(l['text']):                    # headings always stand alone
            flush(); buf.append(l['text']); flush(); continue
        buf.append(l['text'])
        j = nxt.get(i)
        if j is None or HEADING.match(lines[j]['text']):
            flush(); continue
        if l['x1'] + GAP + lines[j]['w0'] <= l['right'] - 1.0:   # next word would have fitted
            flush(); continue
        if re.search(r'[.!?’”\'"—:)\]]$', l['text']) and re.match(r'^[A-Z‘“"—(\[]', lines[j]['text']):
            buf.append(SOFT)
    flush()
    return [re.sub(r'(?<=\w)- (?=[a-z])', '-', p) for p in out]   # "justly- excited" -> "justly-excited"


def run():
    for ed in '13':
        lines = read_lines(work(f'{ed}_bbox.html'))
        paras = paragraphs(lines)
        open(work(f'{ed}_para.txt'), 'w', encoding='utf-8').write('\n'.join(paras) + '\n')
        print(f'  {ed}: {len(lines)} lines -> {len(paras)} paragraphs')

if __name__ == '__main__':
    run()
